#!/usr/bin/env python3
"""Markdown -> PDF in the house report style.

    uv run --no-project --with markdown --with playwright --with pymupdf --with fonttools \
        python ~/.claude/skills/md-to-pdf/md_to_pdf.py "notes/Report 14-10-2026.md"

One-time setup per machine (not per run — cached after):

    uv run --no-project --with playwright playwright install chromium

Style (from `Report 04-10-2026.pdf`): plain white A4 document, dark bold
title, italic subtitle, clickable contents with real page numbers, lavender
section headings (Catppuccin) with an underline, uppercase grey table
headers, real color emoji.

Renders with Playwright driving headless Chromium — real CSS (float,
:nth-child, text-transform, transparent), and critically, real color emoji,
which no pure-Python PDF engine (WeasyPrint, xhtml2pdf/reportlab) can draw at
all: they can only read a font's plain vector outline table, never a font's
color/bitmap glyph data (COLR/CPAL, CBDT, sbix), regardless of which font is
picked. Chromium can. Playwright's Chromium binary installs into a per-user
cache dir (~/.cache/ms-playwright or OS equivalent) via `playwright install`
— no sudo, no system package manager, but it IS a one-time ~100-300MB
download per machine, separate from `uv`'s own per-run package cache.

Fonts (Inter + Noto Color Emoji) are NOT committed to the dotfiles repo —
that's 25MB+ of binary that would bloat its git history forever for every
clone. Instead `ensure_fonts()` downloads them into fonts/ (gitignored) on
first run, the same way `playwright install` caches Chromium outside git.
Subsequent runs reuse the cached files.

The contents page is hand-built, not generated by a browser extension or
print feature — Chromium's print-to-PDF has no built-in "give me each
section's real page number" mechanism either. Renders twice: pass 1 (page
numbers unknown yet) locates each heading's real page by searching its text
with pymupdf, then pass 2 renders the final PDF with a TOC where the whole
row is a real `<a href="#id">` link — which Chromium's print-to-PDF DOES
preserve as a clickable internal PDF link.

Heading mapping:
  first `# H1`               -> document title
  first paragraph after it   -> italic subtitle
  further `# H1`s (if any)   -> lavender sections; `##` -> subsections; `###` -> minor
  no further `# H1`          -> `##` are the lavender sections; `###` -> subsections
Images resolve relative to the markdown file.
"""

import argparse
import os
import re
import sys
import tempfile
import urllib.request

import markdown

FONTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts")

# Not committed to git (see module docstring) — downloaded here on first run.
# Inter: static instances of the variable font, fetched pre-built as woff2
# from Fontsource instead of running `fonttools varLib.instancer` ourselves
# (same bytes, no local instancing step, much smaller than the TTF originals).
FONT_FILES = {
    "Inter-Regular.woff2": "https://cdn.jsdelivr.net/fontsource/fonts/inter@latest/latin-400-normal.woff2",
    "Inter-Bold.woff2": "https://cdn.jsdelivr.net/fontsource/fonts/inter@latest/latin-700-normal.woff2",
    "Inter-Italic.woff2": "https://cdn.jsdelivr.net/fontsource/fonts/inter@latest/latin-400-italic.woff2",
    "Inter-BoldItalic.woff2": "https://cdn.jsdelivr.net/fontsource/fonts/inter@latest/latin-700-italic.woff2",
    # Real COLR/CPAL color font — large (~25MB), no smaller substitute exists
    # that still has these glyphs in color. raw.githubusercontent.com, not
    # jsDelivr's GitHub proxy, which refuses files over 20MB.
    "NotoColorEmoji.ttf": "https://raw.githubusercontent.com/google/fonts/main/ofl/notocoloremoji/NotoColorEmoji-Regular.ttf",
}


def ensure_fonts():
    os.makedirs(FONTS_DIR, exist_ok=True)
    for name, url in FONT_FILES.items():
        path = os.path.join(FONTS_DIR, name)
        if os.path.exists(path) and os.path.getsize(path) > 0:
            continue
        print(f"md-to-pdf: downloading {name} (one-time, cached after)...", file=sys.stderr)
        tmp = path + ".part"
        urllib.request.urlretrieve(url, tmp)
        os.replace(tmp, path)


# Catppuccin Latte, lavender accent (v1.8.0 — see the `catppuccin` skill),
# on a plain white page.
INK = "#4C4F69"        # text
MUTED = "#6C6F85"       # subtext0
ACCENT = "#7287FD"      # lavender
RULE = "#CCD0DA"        # surface0
MANTLE = "#E6E9EF"      # mantle (zebra rows, code background)

# One spacing scale, used everywhere instead of ad-hoc per-element values, so
# vertical rhythm reads as consistent rather than each block picking its own
# gap. XS/SM/MD/LG/XL = 1/2/3/4/6mm.
XS, SM, MD, LG, XL = "1mm", "2mm", "3mm", "4mm", "6mm"

# Same idea for borders: three weights, reused by every element that needs
# one, instead of each picking its own width/color combination.
BORDER_HAIRLINE = f"1px solid {RULE}"      # lightest — data-row dividers (td)
BORDER_STRONG = f"1.3px solid {INK}"       # structural dividers (th, TOC heading)
BORDER_ACCENT = f"1.3px solid {ACCENT}"    # same weight as STRONG, accent color — section headings
BORDER_BAR = f"3px solid {ACCENT}"         # thicker, directional — blockquote's left marker bar


def _css():
    f = FONTS_DIR
    return f"""
@font-face {{ font-family: "Inter"; src: url("file://{f}/Inter-Regular.woff2") format("woff2"); }}
@font-face {{ font-family: "Inter"; font-weight: bold;
              src: url("file://{f}/Inter-Bold.woff2") format("woff2"); }}
@font-face {{ font-family: "Inter"; font-style: italic;
              src: url("file://{f}/Inter-Italic.woff2") format("woff2"); }}
@font-face {{ font-family: "Inter"; font-weight: bold; font-style: italic;
              src: url("file://{f}/Inter-BoldItalic.woff2") format("woff2"); }}
/* Real color emoji — Chromium (unlike any pure-Python PDF engine) can
   render a COLR/CPAL color font natively. Listed as a fallback after Inter
   so plain text still uses Inter and only emoji codepoints fall through. */
@font-face {{ font-family: "Noto Color Emoji"; src: url("file://{f}/NotoColorEmoji.ttf"); }}

* {{ -webkit-print-color-adjust: exact; print-color-adjust: exact; }}

html {{ font-family: "Inter", "Noto Color Emoji"; font-size: 9.6pt; line-height: 1.55;
        color: {INK}; background: white; }}
body {{ margin: 0; }}

h1.title {{ font-size: 22pt; line-height: 1.2; font-weight: bold; margin: 0 0 {SM} 0;
            color: {INK}; }}
p.subtitle {{ font-style: italic; color: {MUTED}; font-size: 10.2pt; margin: 0 0 {LG} 0; }}

/* A separate rule above the heading plus the heading's own accent underline
   was two lines doing one job — just give h2 a top margin for separation
   instead, the underline alone marks a new section starting. */
h2 {{ color: {ACCENT}; font-size: 14.5pt; font-weight: bold; margin: {XL} 0 {MD} 0;
      padding-bottom: 1.6mm; border-bottom: {BORDER_ACCENT}; break-after: avoid-page; }}
h3 {{ font-size: 11.2pt; font-weight: bold; margin: {XL} 0 {SM} 0; color: {INK};
      break-after: avoid-page; }}
h4 {{ font-size: 10pt; font-weight: bold; margin: {LG} 0 {SM} 0; color: {INK};
      break-after: avoid-page; }}

p {{ margin: 0 0 {MD} 0; }}
ul, ol {{ margin: 0 0 {MD} 0; padding-left: 5mm; }}
li {{ margin: 0 0 {XS} 0; }}
em {{ color: {MUTED}; }}
a {{ color: {ACCENT}; }}

code {{ font-family: "Courier New", monospace; font-size: 8.2pt; background-color: {MANTLE};
        padding: 1pt 3pt; border-radius: 2pt; }}
pre {{ background-color: {MANTLE}; padding: {MD}; margin: 0 0 {MD} 0; font-size: 8pt;
       white-space: pre-wrap; border-radius: 2pt; }}
pre code {{ background-color: transparent; padding: 0; }}
blockquote {{ margin: 0 0 {MD} 0; padding: {SM} 0 {SM} {LG}; border-left: {BORDER_BAR};
              color: {MUTED}; }}
/* without this, the <p> inside keeps its own margin-bottom, stacking with
   blockquote's own padding and leaving the bar visibly taller than the text */
blockquote p {{ margin: 0; }}

table {{ border-collapse: collapse; width: 100%; margin: 0 0 {MD} 0; font-size: 8.4pt; }}
th {{ text-align: left; font-size: 7.2pt; font-weight: bold; color: {MUTED};
      text-transform: uppercase; letter-spacing: .4pt;
      padding: {SM}; border-bottom: {BORDER_STRONG}; }}
td {{ padding: {SM}; border-bottom: {BORDER_HAIRLINE}; }}
/* :not(.toc) — a bare <tr> inside any <table> gets auto-wrapped in an
   implicit <tbody> by the browser, so without this the TOC table (which
   also uses plain <tr>s) would pick up zebra striping it was never meant to have */
table:not(.toc) tbody tr:nth-child(even) td {{ background-color: {MANTLE}; }}
tr {{ break-inside: avoid-page; }}

.toc-h {{ font-size: 11.2pt; font-weight: bold; margin: 0 0 {MD} 0; padding-bottom: 1.6mm;
          border-bottom: {BORDER_STRONG}; }}
table.toc {{ width: 100%; border-collapse: collapse; margin: 0; font-size: 9pt; }}
.toc td {{ padding: {XS} 0; border: none; }}
.toc td.num {{ text-align: right; width: 10mm; }}
.toc a {{ text-decoration: none; color: {INK}; display: block; }}
.toc tr.t2 td {{ padding-top: {MD}; }}
.toc tr.t2 a {{ color: {ACCENT}; font-weight: bold; font-size: 10pt; }}
.toc tr.t3 a {{ padding-left: 5mm; font-size: 9pt; color: {MUTED}; }}

figure {{ margin: 0 0 {LG} 0; break-inside: avoid-page; }}
figure img {{ max-width: 100%; display: block; }}
"""


LIST = re.compile(r"^\s*(?:[-*+]|\d+\.)\s")

# Emoji need no special handling — the font-family fallback stack in _css()
# ("Inter", "Noto Color Emoji") is enough for Chromium to pick the right
# font per-character on its own, same as any real browser. That's the point
# of rendering through an actual browser engine instead of hand-patching
# Unicode/font nuances ourselves.
TAG_RE = re.compile(r"<[^>]+>")


def preprocess(md):
    """python-markdown needs a blank line before a list that follows a paragraph."""
    out, fence = [], False
    for ln in md.split("\n"):
        if ln.lstrip().startswith("```"):
            fence = not fence
        prev = out[-1] if out else ""
        if (not fence and LIST.match(ln) and prev.strip() and not LIST.match(prev)
                and not prev.lstrip().startswith("|") and not prev.startswith("  ")):
            out.append("")
        out.append(ln)
    return "\n".join(out)


def restyle(body, title=None, subtitle=True):
    """Returns (head_html, rest_html, entries) — entries is [(level, id, text), ...]
    for every section/subsection heading, left for the caller to turn into a TOC."""
    body = re.sub(r"<p>\s*(<img [^>]+>)\s*</p>", r"<figure>\1</figure>", body)

    m = re.match(r"\s*<h1>(.*?)</h1>", body, re.S)
    if m:
        head = f'<h1 class="title">{title or m.group(1)}</h1>'
        rest = body[m.end():]
        if subtitle:
            p = re.match(r"\s*<p>(.*?)</p>", rest, re.S)
            if p:
                head += f'<p class="subtitle">{p.group(1)}</p>'
                rest = rest[p.end():]
    else:
        head, rest = (f'<h1 class="title">{title}</h1>' if title else ""), body

    if re.search(r"<h1>", rest):          # further H1s are the sections
        rest = re.sub(r"<(/?)h3>", r"<\1h4>", rest)
        rest = re.sub(r"<(/?)h2>", r"<\1h3>", rest)
        rest = re.sub(r"<(/?)h1>", r"<\1h2>", rest)

    entries, n = [], [0]

    def tag(mm):
        n[0] += 1
        sid = f"sec{n[0]}"
        entries.append((mm.group(1), sid, mm.group(2)))
        return f'<h{mm.group(1)} id="{sid}">{mm.group(2)}</h{mm.group(1)}>'

    rest = re.sub(r"<h([23])>(.*?)</h\1>", tag, rest, flags=re.S)
    return head, rest, entries


def build_toc_html(entries, pages=None):
    """pages: dict sid -> page number string, or None to render placeholders
    (pass 1, just to learn real page numbers without affecting their layout).
    Each row is a <table> tr with the whole label cell AND the page-number
    cell wrapped in the same <a href="#id"> link, so (nearly) the full row
    width is clickable and Chromium's print-to-PDF preserves it as a real
    internal PDF link."""
    if not entries:
        return ""
    rows = []
    for level, sid, text in entries:
        label = TAG_RE.sub("", text)
        num = (pages or {}).get(sid, "0")
        rows.append(
            f'<tr class="t{level}">'
            f'<td><a href="#{sid}">{label}</a></td>'
            f'<td class="num"><a href="#{sid}">{num}</a></td>'
            f'</tr>'
        )
    toc = ('<div class="toc-h">Contents</div>'
           '<table class="toc">' + "".join(rows) + "</table>")
    return f'<div style="break-after: page;">{toc}</div>'


def render(head, rest, toc_html, base_dir):
    return (f"<html><head><meta charset='utf-8'>"
            f"<base href='file://{base_dir}/'>"
            f"<style>{_css()}</style></head>"
            f"<body>{head}{toc_html}{rest}</body></html>")


PDF_MARGINS = {"top": "16mm", "bottom": "18mm", "left": "16mm", "right": "16mm"}


def locate_pages(pdf_bytes, entries):
    """Open a rendered pass-1 PDF and find each heading's real page number by
    searching for its (tag-stripped) text, in document order. Starts the
    search on page 2 (index 1) — page 1 is always the TOC itself (hard
    page-break after it), and it contains the same heading labels as link
    text, which would otherwise match before the real heading does."""
    import fitz  # pymupdf
    pages, search_from = {}, 1
    with fitz.open(stream=pdf_bytes, filetype="pdf") as doc:
        for _, sid, text in entries:
            label = TAG_RE.sub("", text)
            found = None
            for i in range(search_from, doc.page_count):
                if doc[i].search_for(label):
                    found = i + 1
                    search_from = i
                    break
            pages[sid] = str(found) if found else "?"
    return pages


def _font_cmap(path):
    from fontTools.ttLib import TTFont
    return set(TTFont(path, lazy=True).getBestCmap())


_COVERED_CODEPOINTS = None


def check_unsupported_chars(text):
    """Inter + Noto Color Emoji (downloaded by ensure_fonts() into fonts/,
    gitignored) cover Latin/Cyrillic/Greek/etc plus every common emoji, but
    not everything (CJK, for one — Inter doesn't cover it, and it'd render
    as a blank box with no error, even though Chromium itself could draw it
    via a system font if one happens to be installed on this particular
    machine — this check only counts what's guaranteed present on ANY
    machine via the bundled fonts, not what this one happens to have)."""
    global _COVERED_CODEPOINTS
    if _COVERED_CODEPOINTS is None:
        _COVERED_CODEPOINTS = (
            _font_cmap(os.path.join(FONTS_DIR, "Inter-Regular.woff2"))
            | _font_cmap(os.path.join(FONTS_DIR, "NotoColorEmoji.ttf"))
        )
    bad = {}
    for ch in text:
        if ch in "\n\r\t" or ord(ch) == 0xFE0F:  # variation selector, invisible
            continue
        if ord(ch) not in _COVERED_CODEPOINTS:
            bad.setdefault(ch, 0)
            bad[ch] += 1
    if not bad:
        return None
    sample = ", ".join(f"'{c}' (U+{ord(c):04X}, x{n})" for c, n in list(bad.items())[:6])
    more = f", +{len(bad) - 6} more" if len(bad) > 6 else ""
    return (f"warning: {len(bad)} character(s) not covered by the bundled fonts may render "
            f"as blank boxes: {sample}{more}. CJK and some other scripts aren't covered "
            f"(see md-to-pdf's SKILL.md).")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("markdown", help="input .md file")
    ap.add_argument("-o", "--out", help="output .pdf (default: same name next to the input)")
    ap.add_argument("--title", help="override the document title (default: first # heading)")
    ap.add_argument("--no-toc", action="store_true", help="omit the contents page")
    ap.add_argument("--no-subtitle", action="store_true",
                    help="keep the first paragraph as body text instead of an italic subtitle")
    a = ap.parse_args()

    src = os.path.abspath(a.markdown)
    if not os.path.isfile(src):
        sys.exit(f"no such file: {src}")
    out = os.path.abspath(a.out) if a.out else os.path.splitext(src)[0] + ".pdf"
    base_dir = os.path.dirname(src)

    ensure_fonts()

    src_text = open(src, encoding="utf-8").read()
    md = preprocess(src_text)
    body = markdown.markdown(md, extensions=["tables", "fenced_code", "sane_lists"])
    head, rest, entries = restyle(body, title=a.title, subtitle=not a.no_subtitle)

    # Checked post-restyle (not the raw source) so content that's already
    # been handled (e.g. emoji, already real glyphs) can't false-positive.
    warning = check_unsupported_chars(TAG_RE.sub("", head + rest))
    if warning:
        print(warning, file=sys.stderr)

    from playwright.sync_api import sync_playwright

    want_toc = not a.no_toc and bool(entries)
    with tempfile.NamedTemporaryFile(suffix=".html", delete=False) as tmp:
        tmp_path = tmp.name
    try:
        with sync_playwright() as p:
            try:
                browser = p.chromium.launch()
            except Exception as e:
                sys.exit(f"Couldn't launch Chromium ({e}). Run this once per machine: "
                        f"uv run --no-project --with playwright playwright install chromium")
            page = browser.new_page()

            if want_toc:
                # Pass 1: placeholder page numbers, just to measure where things land.
                with open(tmp_path, "w", encoding="utf-8") as f:
                    f.write(render(head, rest, build_toc_html(entries), base_dir))
                page.goto(f"file://{tmp_path}")
                pdf1_bytes = page.pdf(format="A4", margin=PDF_MARGINS, print_background=True)
                pages = locate_pages(pdf1_bytes, entries)
                toc_html = build_toc_html(entries, pages)
            else:
                toc_html = ""

            with open(tmp_path, "w", encoding="utf-8") as f:
                f.write(render(head, rest, toc_html, base_dir))
            page.goto(f"file://{tmp_path}")
            page.pdf(path=out, format="A4", margin=PDF_MARGINS, print_background=True)
            browser.close()
    finally:
        os.unlink(tmp_path)

    print(out)


if __name__ == "__main__":
    main()
